"""Compare policy retrieval backends on a labelled query set.

    python -m quilora.search.compare            # all backends that are available
    python -m quilora.search.compare --write    # also update docs/results/retrieval.md

Metrics (k = 3, the number of sections the tool returns by default):
  Hit@1   share of queries whose first result is relevant
  Hit@3   share of queries with a relevant result in the top 3 (what the model sees)
  MRR     mean reciprocal rank of the first relevant result (top 10)
  p50 ms  median latency per query, including the embedding of the query
"""

from __future__ import annotations

import argparse
import statistics
import time
from collections import defaultdict
from datetime import date

import psycopg
import yaml
from psycopg.rows import dict_row

from quilora.config import load_settings
from quilora.paths import DOCS_DIR, EVALS_DIR, PROJECT_ROOT
from quilora.search.policies import embeddings_available, search_fts, search_hybrid, search_vector

QUERIES = EVALS_DIR / "retrieval" / "queries.yaml"
RESULTS = DOCS_DIR / "results" / "retrieval.md"


def evaluate(conn, queries: list[dict], backend: str, embedder=None) -> dict:
    per_group: dict[str, list[dict]] = defaultdict(list)
    for q in queries:
        started = time.perf_counter()
        if backend == "fts":
            hits = search_fts(conn, q["query"], 10)
        elif backend == "vector":
            hits = search_vector(conn, q["query"], 10, embedder)
        else:
            hits = search_hybrid(conn, q["query"], 10, embedder)
        elapsed = (time.perf_counter() - started) * 1000
        ids = [h.chunk_id for h in hits]
        rank = next((i for i, cid in enumerate(ids, start=1) if cid in q["relevant"]), None)
        row = {"query": q["query"], "rank": rank, "top": ids[:3], "ms": elapsed}
        per_group[q["group"]].append(row)
        per_group["ALL"].append(row)

    def summarise(rows: list[dict]) -> dict:
        n = len(rows)
        return {
            "n": n,
            "hit1": sum(r["rank"] == 1 for r in rows) / n,
            "hit3": sum(r["rank"] is not None and r["rank"] <= 3 for r in rows) / n,
            "mrr": sum(1 / r["rank"] for r in rows if r["rank"]) / n,
            "p50_ms": statistics.median(r["ms"] for r in rows),
            "misses": [r["query"] for r in rows if not r["rank"] or r["rank"] > 3],
        }

    return {group: summarise(rows) for group, rows in per_group.items()}


def to_markdown(results: dict[str, dict], model_name: str | None, skipped: list[str]) -> str:
    groups = ["ALL", "en_keyword", "en_paraphrase", "es"]
    lines = [
        "# Policy retrieval: FTS vs vector vs hybrid",
        "",
        f"Generated by `python -m quilora.search.compare --write` on {date.today().isoformat()}.",
        f"Queries: `evals/retrieval/queries.yaml`. Embedding model: `{model_name or 'n/a'}`.",
        "",
        "| Backend | Group | n | Hit@1 | Hit@3 | MRR | p50 ms |",
        "|---------|-------|---|-------|-------|-----|--------|",
    ]
    for backend, by_group in results.items():
        for g in groups:
            if g in by_group:
                m = by_group[g]
                lines.append(f"| {backend} | {g} | {m['n']} | {m['hit1']:.2f} | {m['hit3']:.2f} "
                             f"| {m['mrr']:.2f} | {m['p50_ms']:.1f} |")
    if skipped:
        lines += ["", f"Not run (no embeddings in the database): {', '.join(skipped)}. Run "
                      "`make embed` (needs the `embeddings` extra) and run the comparison again."]
    for backend, by_group in results.items():
        misses = by_group["ALL"]["misses"]
        lines += ["", f"**{backend}: misses at k=3 ({len(misses)})**", ""]
        lines += [f"- {q}" for q in misses] or ["- none"]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="update docs/results/retrieval.md")
    args = parser.parse_args()
    settings = load_settings()
    queries = yaml.safe_load(QUERIES.read_text(encoding="utf-8"))

    results: dict[str, dict] = {}
    skipped: list[str] = []
    model_name = None
    with psycopg.connect(settings.database_url, row_factory=dict_row) as conn:
        results["fts"] = evaluate(conn, queries, "fts")
        if embeddings_available(conn):
            from quilora.search.embeddings import FastEmbedEmbedder

            embedder = FastEmbedEmbedder(settings.embedding_model)
            model_name = embedder.model_name
            results["vector"] = evaluate(conn, queries, "vector", embedder)
            results["hybrid"] = evaluate(conn, queries, "hybrid", embedder)
        else:
            skipped = ["vector", "hybrid"]

    report = to_markdown(results, model_name, skipped)
    print(report)
    if args.write:
        RESULTS.parent.mkdir(parents=True, exist_ok=True)
        RESULTS.write_text(report, encoding="utf-8")
        print(f"Wrote {RESULTS.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
